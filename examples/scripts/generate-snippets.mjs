import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHighlighter } from 'shiki';
import { snippetSources } from '../shared/snippets-source.js';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const outputFile = resolve(scriptDir, '../shared/snippets.js');

function extractCodeInnerHtml(html) {
  const match = html.match(/<code>([\s\S]*?)<\/code>/);
  if (!match) {
    throw new Error('Unable to extract <code> content from highlighted HTML.');
  }
  return match[1];
}

function toModuleSource(snippets) {
  return `// This file is generated by examples/scripts/generate-snippets.mjs\nexport const snippets = ${JSON.stringify(snippets, null, 2)};\n`;
}

async function main() {
  const highlighter = await createHighlighter({
    themes: ['github-dark'],
    langs: ['ts', 'tsx', 'astro'],
  });

  const snippets = {};
  for (const [key, snippet] of Object.entries(snippetSources)) {
    const highlighted = highlighter.codeToHtml(snippet.text, {
      lang: snippet.lang,
      theme: 'github-dark',
    });

    snippets[key] = {
      text: snippet.text,
      html: extractCodeInnerHtml(highlighted),
    };
  }

  await writeFile(outputFile, toModuleSource(snippets), 'utf8');
  console.log(`Generated ${outputFile}`);
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`snippets:generate failed: ${message}`);
  process.exit(1);
});
